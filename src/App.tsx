import { useState, useEffect } from 'react';
import { Sidebar } from './components/layout/Sidebar';
import { Topbar } from './components/layout/Topbar';
import { DashboardPage } from './pages/DashboardPage';
import { NewReviewPage } from './pages/NewReviewPage';
import { AnalysisResultsPage } from './pages/AnalysisResultsPage';
import { ReviewHistoryPage } from './pages/ReviewHistoryPage';
import { BrandGuidelinesPage } from './pages/BrandGuidelinesPage';
import { EvidenceLibraryPage } from './pages/EvidenceLibraryPage';
import { StorageService } from './storage/localStorage';
import type { ReviewRecord, BrandRule, EvidenceRecord } from './types';
import { Info } from 'lucide-react';
import './App.css';

export function App() {
  const [currentTab, setCurrentTab] = useState<string>('dashboard');
  const [currentReviewId, setCurrentReviewId] = useState<string>('#BG-8924');
  const [reviews, setReviews] = useState<ReviewRecord[]>([]);
  const [rules, setRules] = useState<BrandRule[]>([]);
  const [evidenceList, setEvidenceList] = useState<EvidenceRecord[]>([]);
  const [searchQuery, setSearchQuery] = useState('');

  // Initialize storage safely on mount
  useEffect(() => {
    StorageService.initialize();
    refreshData();
  }, []);

  const refreshData = () => {
    setReviews(StorageService.getReviews());
    setRules(StorageService.getRules());
    setEvidenceList(StorageService.getEvidence());
  };

  const handleResetDemo = () => {
    if (window.confirm('Reset all demo workspace data back to factory Acme Global 2025 defaults?')) {
      StorageService.resetToDemo();
      refreshData();
      setCurrentReviewId('#BG-8924');
      setCurrentTab('dashboard');
    }
  };

  const handleOpenReview = (reviewId: string) => {
    setCurrentReviewId(reviewId);
    setCurrentTab('analysis');
    window.scrollTo({ top: 0, behavior: 'smooth' });
  };

  const handleScanComplete = (newReviewId: string) => {
    refreshData();
    setCurrentReviewId(newReviewId);
    setCurrentTab('analysis');
    window.scrollTo({ top: 0, behavior: 'smooth' });
  };

  const handleReviewUpdated = (updatedReview: ReviewRecord) => {
    setReviews(prev => prev.map(r => (r.id === updatedReview.id ? updatedReview : r)));
  };

  const handleToggleRule = (ruleId: string) => {
    StorageService.toggleRuleActive(ruleId);
    refreshData();
  };

  const handleAddRule = (newRule: BrandRule) => {
    StorageService.addRule(newRule);
    refreshData();
  };

  const handleAddEvidence = (newRecord: EvidenceRecord) => {
    StorageService.addEvidence(newRecord);
    refreshData();
  };

  // Find active review for analysis view
  const activeReview = reviews.find(r => r.id === currentReviewId) || reviews[0];

  // Dynamic breadcrumbs based on navigation
  const getBreadcrumbs = () => {
    const root = { label: 'BrandGuard AI', action: () => setCurrentTab('dashboard') };
    switch (currentTab) {
      case 'dashboard':
        return [root, { label: 'Dashboard', active: true }];
      case 'new-review':
        return [
          root, 
          { label: 'Reviews', action: () => setCurrentTab('history') }, 
          { label: 'New Review', active: true }
        ];
      case 'analysis':
        return [
          root, 
          { label: 'Reviews', action: () => setCurrentTab('history') }, 
          { label: activeReview ? `${activeReview.id} (${activeReview.campaignName.slice(0, 18)}...)` : '#BG-8924' }, 
          { label: 'Analysis Results', active: true }
        ];
      case 'history':
        return [root, { label: 'Review History', active: true }];
      case 'guidelines':
        return [root, { label: 'Brand Guidelines', active: true }];
      case 'evidence':
        return [root, { label: 'Evidence Library', active: true }];
      default:
        return [root];
    }
  };

  return (
    <div className="app-container">
      {/* Sidebar Navigation */}
      <Sidebar
        currentTab={currentTab}
        onNavigate={(tab) => {
          setCurrentTab(tab);
          window.scrollTo({ top: 0, behavior: 'smooth' });
        }}
        rulesCount={rules.filter(r => r.isActive).length}
        onResetDemo={handleResetDemo}
      />

      {/* Main Viewport */}
      <div className="main-viewport">
        {/* Top Notice banner */}
        <div className="demo-top-notice">
          <Info size={14} />
          <span>This content was generated by a Stitch user. Do not enter sensitive information as it may be seen by the owner.</span>
        </div>

        {/* Topbar */}
        <Topbar
          breadcrumb={getBreadcrumbs()}
          policyVersion="Acme Global 2025 Guidelines v2.4"
          onNewReviewClick={() => {
            setCurrentTab('new-review');
            window.scrollTo({ top: 0, behavior: 'smooth' });
          }}
          searchQuery={searchQuery}
          onSearchChange={setSearchQuery}
        />

        {/* Dynamic Page Views */}
        <main>
          {currentTab === 'dashboard' && (
            <DashboardPage
              reviews={reviews}
              rulesCount={rules.filter(r => r.isActive).length}
              onOpenReview={handleOpenReview}
              onNewReview={() => setCurrentTab('new-review')}
              onOpenGuidelines={() => setCurrentTab('guidelines')}
            />
          )}

          {currentTab === 'new-review' && (
            <NewReviewPage
              rules={rules}
              evidenceList={evidenceList}
              onScanComplete={handleScanComplete}
            />
          )}

          {currentTab === 'analysis' && activeReview && (
            <AnalysisResultsPage
              review={activeReview}
              rules={rules}
              evidenceList={evidenceList}
              onReviewUpdated={handleReviewUpdated}
              onNavigateHistory={() => setCurrentTab('history')}
            />
          )}

          {currentTab === 'history' && (
            <ReviewHistoryPage
              reviews={reviews}
              onOpenReview={handleOpenReview}
              onNewReview={() => setCurrentTab('new-review')}
            />
          )}

          {currentTab === 'guidelines' && (
            <BrandGuidelinesPage
              rules={rules}
              onToggleRule={handleToggleRule}
              onAddRule={handleAddRule}
            />
          )}

          {currentTab === 'evidence' && (
            <EvidenceLibraryPage
              evidenceList={evidenceList}
              onAddEvidence={handleAddEvidence}
            />
          )}
        </main>
      </div>
    </div>
  );
}

export default App;
